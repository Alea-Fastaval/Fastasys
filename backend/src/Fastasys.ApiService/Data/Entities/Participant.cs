using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Text.Json.Serialization;

namespace Fastasys.ApiService.Data.Entities;

/// <summary>
/// A participant (Infosys: deltagere). Only the columns Infosys still uses are ported; the column list was
/// approved on 2026-11-11. Columns that belong to features not ported yet (login password, payment hash, app
/// token, pricing, check-in balance, hero force contact, signup consent) are added with those features.
/// </summary>
[Table("participants")]
public class Participant
{
    // Not generated by the database when created through the API: ParticipantRules.LowestFreeId picks the
    // lowest free id, like Infosys. The identity default is kept as a fallback for other code paths.
    public int Id { get; set; }

    [MaxLength(128)]
    public string FirstName { get; set; } = string.Empty;

    [MaxLength(256)]
    public string LastName { get; set; } = string.Empty;

    [MaxLength(255)]
    public string Nickname { get; set; } = string.Empty;

    [MaxLength(512)]
    public string Email { get; set; } = string.Empty;

    // Infosys: mobiltlf
    [MaxLength(32)]
    public string PhoneNumber { get; set; } = string.Empty;

    // Infosys: adresse1 / adresse2
    [MaxLength(128)]
    public string AddressLine1 { get; set; } = string.Empty;

    [MaxLength(128)]
    public string AddressLine2 { get; set; } = string.Empty;

    [MaxLength(32)]
    public string ZipCode { get; set; } = string.Empty;

    [MaxLength(128)]
    public string City { get; set; } = string.Empty;

    // Infosys: country, default DK
    [MaxLength(2)]
    public string CountryCode { get; set; } = "DK";
    public virtual Country Country { get; set; } = null!;

    // null means unknown (Infosys stores 0000-00-00)
    public DateOnly? BirthDate { get; set; }

    // Infosys codes: "none", "ask", or one or two of ns/no/fs/fo/ms/mo (e.g. "nsno")
    [MaxLength(4)]
    public string Pronouns { get; set; } = "none";

    // Infosys: main_lang
    public PreferredLanguage PreferredLanguage { get; set; } = PreferredLanguage.Danish;

    // Infosys: sprog, the languages the participant can play activities in. Default dansk.
    public List<ParticipantLanguage> ActivityLanguages { get; set; } = [ParticipantLanguage.Danish];

    // Infosys: sleeping_area, the sleeping areas wished for in the signup
    public List<SleepingArea> SleepingAreas { get; set; } = [];

    // Infosys: ungdomsskole
    [MaxLength(128)]
    public string YouthClub { get; set; } = string.Empty;

    public bool PhotoConsent { get; set; }

    // Infosys: medbringer_mobil ("Tilmeldt SMS")
    public bool SmsSignup { get; set; }

    // Infosys: brugerkategori_id
    public int CategoryId { get; set; } = ParticipantCategory.ParticipantId;
    public virtual ParticipantCategory Category { get; set; } = null!;

    // Infosys: work_area
    public int? OrganizerAreaId { get; set; }
    public virtual OrganizerArea? OrganizerArea { get; set; }

    // Infosys: forfatter ("Forfatter/Designer")
    public bool IsAuthorOrDesigner { get; set; }

    // Infosys: game_id, the scenario or board game the participant wrote or designed
    public int? GameActivityId { get; set; }
    public virtual Activity? GameActivity { get; set; }

    public int ExtraVouchers { get; set; }

    public int DesiredActivities { get; set; }

    // Infosys: desired_diy_shifts
    public int DesiredHeroTasks { get; set; }

    // Infosys: supergm, gm_max, junior_gm, super_rules_guide, rules_guide_max, supergds
    public bool SuperGameMaster { get; set; }
    public int? MaxGameMasterRuns { get; set; }
    public bool JuniorGameMaster { get; set; }
    public bool SuperRulesGuide { get; set; }
    public int? MaxRulesGuideGames { get; set; }
    public bool SuperHero { get; set; }

    // Infosys: ready_mandag / ready_tirsdag
    public bool SetupHelpMonday { get; set; }
    public bool SetupHelpTuesday { get; set; }

    // Infosys: financial_struggle
    public bool FinancialSupport { get; set; }

    // Infosys: udeblevet, annulled, activity_lock
    public bool IsNoShow { get; set; }
    public bool IsAnnulled { get; set; }
    public bool IsActivityLocked { get; set; }

    // Stored in UTC
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
    public DateTime SignedUpAt { get; set; } = DateTime.UtcNow;

    // null means not checked in (Infosys stores 0000-00-00 00:00:00)
    public DateTime? CheckedInAt { get; set; }

    // Infosys: betalt_beloeb ("Forudbetalt"). Whole DKK, like Infosys.
    public int AmountPaid { get; set; }

    // Infosys: admin_note, beskeder, paid_note
    public string AdminNote { get; set; } = string.Empty;
    public string MessageToParticipant { get; set; } = string.Empty;
    public string PaymentNote { get; set; } = string.Empty;

    // Infosys: deltager_note, a JSON object with the notes given in the signup. Each key is a column here; null
    // means the participant didn't give that note (the key is missing in Infosys).
    public string? CommentNote { get; set; }
    public string? HeroForceNote { get; set; }
    public string? JuniorContact { get; set; }
    public string? JuniorComment { get; set; }
    public string? SleepingNote { get; set; }

    public virtual ICollection<ScheduleSignup> Signups { get; set; } = new List<ScheduleSignup>();
    public virtual ICollection<Payment> Payments { get; set; } = new List<Payment>();
    public virtual ICollection<ParticipantFood> Foods { get; set; } = new List<ParticipantFood>();
    public virtual ICollection<ParticipantWear> Wears { get; set; } = new List<ParticipantWear>();

    // Infosys Deltagere::getName: the nickname, or else the legal name
    public string DisplayName()
    {
        return Nickname == string.Empty ? LegalName() : Nickname;
    }

    public string LegalName()
    {
        return FirstName + " " + LastName;
    }
}

/// <summary>Infosys deltagere.main_lang: da, en.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<PreferredLanguage>))]
public enum PreferredLanguage
{
    Danish,
    English
}

/// <summary>Infosys deltagere.sprog: dansk, engelsk, skandinavisk.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<ParticipantLanguage>))]
public enum ParticipantLanguage
{
    Danish,
    English,
    Scandinavian
}

/// <summary>Infosys deltagere.sleeping_area: regular, sober, youth, organizer, family.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<SleepingArea>))]
public enum SleepingArea
{
    Regular,
    Sober,
    Youth,
    Organizer,
    Family
}
